def _orca_input(tmp_path):
    model='''<model xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" unit="millimeter"><resources><object id="1" name="all_cyan" type="model"><mesh><vertices><vertex x="0" y="0" z="0"/><vertex x="10" y="0" z="0"/><vertex x="0" y="10" z="1"/></vertices><triangles><triangle v1="0" v2="1" v3="2"/></triangles></mesh></object></resources><build><item objectid="1"/></build></model>'''
    source=tmp_path/'input.3mf'
    with zipfile.ZipFile(source,'w') as z:
        z.writestr('3D/3dmodel.model',model)
        z.writestr('[Content_Types].xml','<Types></Types>')
        z.writestr('Metadata/layerloom_contour.json',json.dumps(dict(layer_height=.08,first_layer_height=.16,source_bounds=[[0,0,0],[10,10,1]])))
    profile=tmp_path/'profile.json'
    profile.write_text(json.dumps(dict(machine_start_gcode='G28\nM83',initial_layer_line_width='0.5',detect_thin_wall='0',elefant_foot_compensation='0.15')))
    return source,profile


def test_orca_staging_preserves_machine_gcode_and_maps_slots(tmp_path,monkeypatch):
    import xml.etree.ElementTree as ET
    from layerloom import contour_benchmark as module
    source,profile=_orca_input(tmp_path)
    def measured(command,log,**kwargs):
        assert command[command.index('--slice')+1]=='1'
        with zipfile.ZipFile(command[-1]) as z:
            settings=json.loads(z.read('Metadata/project_settings.config'))
            assert settings['machine_start_gcode']=='G28\nM83'
            assert settings['first_layer_height']=='0.16' and settings['layer_height']=='0.08'
            assert settings['initial_layer_line_width']=='0.5' and settings['detect_thin_wall']=='0'
            config=ET.fromstring(z.read('Metadata/model_settings.config'))
            assert config.find(".//part/metadata[@key='extruder']").get('value')=='1'
            root=ET.fromstring(z.read('3D/3dmodel.model'))
            build=root.find('{*}build/{*}item')
            assert [float(x) for x in build.get('transform').split()][9:]==[130,130,0]
            assert len(root.findall('.//{*}triangle'))==1
        out=Path(command[command.index('--outputdir')+1]);(out/'plate_1.gcode').write_text('; generated by test slicer\nG1 X0 Y0 E1\n')
        return dict(exit_code=0,command=command)
    monkeypatch.setattr(module,'run_measured',measured)
    result=module.slice_orca(source,tmp_path/'out.gcode',profile)
    assert result['full_slice_completed'] and not result['printer_custom_gcode_changed']
    assert result['slicer_generator']=='generated by test slicer'
    assert result['overrides']['elefant_foot_compensation']=='0.15'


def test_orca_import_only_is_not_full_slice(tmp_path,monkeypatch):
    from layerloom import contour_benchmark as module
    source,profile=_orca_input(tmp_path)
    monkeypatch.setattr(module,'run_measured',lambda command,*a,**kw:dict(exit_code=0,command=command))
    with pytest.raises(RuntimeError,match='full slicing failed'):
        module.slice_orca(source,tmp_path/'out.gcode',profile)
    report=json.loads((tmp_path/'out.slice.json').read_text())
    assert report['full_slice_completed'] is False
    assert report['input']['sha256'] and report['overrides']['layer_height']=='0.08'

def test_summary_preserves_failed_and_untested_gates(tmp_path):
    from layerloom.contour_benchmark import summarize_evidence
    failed=tmp_path/'slice.json';failed.write_text(json.dumps(dict(full_slice_completed=False,exit_code=156,elapsed_s=1)))
    walls=tmp_path/'walls.json';walls.write_text(json.dumps(dict(wall_paths_validated=False,layers=10,failed_layers=2,max_displacement_upper_mm=.1)))
    result=summarize_evidence([], [failed], [walls], tmp_path/'report')
    assert result['gates']['full_slicing']=='failed' and result['gates']['wall_preservation']=='failed'
    assert result['gates']['visual_inspection']=='pending'
    assert 'FAILED' in (tmp_path/'report/report.md').read_text()
    empty=summarize_evidence([],[],[],tmp_path/'empty')
    assert empty['gates']['wall_preservation']=='untested'

def test_cancel_stops_worker_that_ignores_sigterm(tmp_path,monkeypatch):
    import time
    from layerloom import contour_benchmark as module
    pytest.importorskip('psutil')
    real_sleep=time.sleep;interrupted=False
    def interrupt_once(seconds):
        nonlocal interrupted
        if not interrupted:
            interrupted=True;real_sleep(.3);raise KeyboardInterrupt
        real_sleep(seconds)
    monkeypatch.setattr(module.time,'sleep',interrupt_once)
    start=time.monotonic()
    with pytest.raises(KeyboardInterrupt):
        module.run_measured([sys.executable,'-c','import signal,time;signal.signal(signal.SIGTERM,signal.SIG_IGN);print("ready",flush=True);time.sleep(30)'],tmp_path/'cancel.log')
    assert time.monotonic()-start<8
    assert 'ready' in (tmp_path/'cancel.log').read_text()

def test_concurrent_benchmark_directory_is_rejected(tmp_path):
    from layerloom.contour_benchmark import _exclusive_benchmark
    @_exclusive_benchmark
    def inner(source,directory):return 'ok'
    @_exclusive_benchmark
    def outer(source,directory):
        with pytest.raises(RuntimeError,match='already locked'):inner(source,directory)
        return 'completed'
    assert outer('source',tmp_path)=='completed'
    assert not (tmp_path/'.benchmark.lock').exists()
    assert inner('source',tmp_path)=='ok'
