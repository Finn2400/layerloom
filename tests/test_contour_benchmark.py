import json
from pathlib import Path
import sys
import zipfile
import pytest
from layerloom.contour_benchmark import artifact_metrics,run_measured

def test_artifact_counts_stream_all_resources(tmp_path):
    p=tmp_path/'mesh.3mf'
    model='<model><resources><object><mesh><vertices><vertex/><vertex/><vertex/></vertices><triangles><triangle/></triangles></mesh></object></resources></model>'
    with zipfile.ZipFile(p,'w') as z:
        z.writestr('3D/3dmodel.model',model);z.writestr('3D/other.model',model)
    result=artifact_metrics(p)
    assert result['vertices']==6 and result['triangles']==2
    assert result['zip_valid'] and result['uncompressed_geometry_bytes']==2*len(model)
    assert len(result['sha256'])==64

def test_measured_process_records_exit_and_observed_memory(tmp_path):
    pytest.importorskip('psutil')
    r=run_measured([sys.executable,'-c','import time; x=bytearray(1000000); print("done",flush=True);time.sleep(.15)'],tmp_path/'job.log')
